'use strict';
const assert=require('node:assert/strict'),path=require('node:path'),fs=require('node:fs'),os=require('node:os');
const dir=process.env.PALE_RUNTIME_ROOT?path.resolve(process.env.PALE_RUNTIME_ROOT):path.resolve(__dirname,'../../../runtime');
const {prepare}=require(path.join(dir,'prepare.cjs')),{Client}=require(path.join(dir,'client.cjs'));
const app=path.resolve(__dirname,'..'),appId='home-repair-slots';
const at0=require('../fixtures/clock.json').initial_time;
const event=require('../examples/scenario.json');
const staged=prepare(app),state=fs.mkdtempSync(path.join(os.tmpdir(),'home-repair-core-')),clients=[];
const make=(role,run='happy')=>{const c=new Client(appId,role,run,state,'repair-core-test',{registry:staged.registry,...(role==='infra'?{initialProfile:'sandbox'}:{})});clients.push(c);return c;};
const expect=(r,s='ok')=>{assert.equal(r.status,s,JSON.stringify(r));return r;};
const use=(c,name,args={})=>c.call(appId+'.'+name,args);
const snap=infra=>infra.call('env.snapshot');
const only=s=>[s.snapshot.data,s.snapshot.resources,s.snapshot.virtual_now];

async function main(){
 const launcher=new Client(appId,'infra','launcher-smoke',state,'repair-launcher-smoke',{service:path.join(app,'service.cjs'),initialProfile:'sandbox'});
 clients.push(launcher);await launcher.initialize();
 assert.deepEqual((await snap(launcher)).snapshot.data.history,require('../fixtures/minimal.json').history);
 const i=make('infra'), a=make('agent'), resumed=make('agent');
 await Promise.all([i,a,resumed].map(c=>c.initialize()));
 const empty=expect(await snap(i));
 const load=expect(await i.call('env.load_seed',{expected_version:empty.version,request_id:'seed',data:empty.snapshot.data,bundle:empty.snapshot.resources.bundle,virtual_now:at0}),'ready');
 const initial=expect(await snap(i));
 const discovery=(await a.request('tools/list')).result.tools.map(x=>x.name);
 assert.equal(discovery.length,8);assert.ok(discovery.every(x=>x.startsWith(appId+'.')));
 expect(await a.call('env.apply_event',{}),'permission_denied');
 const available=expect(await use(a,'list_slots'));assert.deepEqual(available.slots.map(x=>x.id),['S1','S2','S4']);
 expect(await use(a,'select_slot',{slot_id:'S3',expected_version:available.version,request_id:'over-budget'}),'outside_constraints');
 assert.deepEqual(only(await snap(i)),only(initial));
 const chosen=expect(await use(a,'select_slot',{slot_id:'S1',expected_version:load.version,request_id:'first-choice'}),'committed');
 assert.equal((await use(resumed,'get_reservation',{reservation_id:chosen.reservation.id})).reservation.status,'open');
 const chosenE={expected_version:chosen.version,event};
 const taken=expect(await i.call('env.apply_event',chosenE),'committed');
 assert.equal((await i.call('env.apply_event',chosenE)).duplicate,true);
 expect(await use(resumed,'confirm_reservation',{reservation_id:chosen.reservation.id,expected_version:chosen.version,request_id:'stale'}),'stale_version');
 const current=expect(await use(resumed,'get_reservation',{reservation_id:chosen.reservation.id}));
 assert.equal(current.reservation.status,'invalidated');assert.deepEqual(current.version,taken.version);
 expect(await use(resumed,'confirm_reservation',{reservation_id:chosen.reservation.id,expected_version:current.version,request_id:'taken'}),'slot_unavailable');
 assert.deepEqual(expect(await use(resumed,'list_slots')).booking_ids,available.booking_ids);
 const alternative=expect(await use(resumed,'select_slot',{slot_id:'S2',expected_version:taken.version,request_id:'alt'}),'committed');
 const cargs={reservation_id:alternative.reservation.id,expected_version:alternative.version,request_id:'confirm'};
 const booked=expect(await use(resumed,'confirm_reservation',cargs),'committed');assert.equal(booked.booking.id,'B5');
 assert.deepEqual(await use(resumed,'confirm_reservation',cargs),{...booked,duplicate:true});
 expect(await use(resumed,'confirm_reservation',{...cargs,reservation_id:chosen.reservation.id}),'idempotency_conflict');
 expect(await use(resumed,'confirm_reservation',{...cargs,expected_version:booked.version,request_id:'fresh'}),'already_confirmed');
 const unchanged=expect(await snap(i));
 expect(await use(resumed,'reschedule_booking',{booking_id:booked.booking.id,slot_id:'S5',expected_version:booked.version,request_id:'fail-move'}),'slot_unavailable');
 assert.deepEqual(only(await snap(i)),only(unchanged));
 const moved=expect(await use(resumed,'reschedule_booking',{booking_id:booked.booking.id,slot_id:'S4',expected_version:booked.version,request_id:'move'}),'committed');
 assert.equal(moved.booking.slot_id,'S4');assert.ok((await use(resumed,'list_slots')).slots.some(x=>x.id==='S2'));
 const cancelled=expect(await use(resumed,'cancel_booking',{booking_id:booked.booking.id,expected_version:moved.version,request_id:'cancel'}),'committed');
 assert.equal((await use(a,'get_booking',{booking_id:booked.booking.id})).booking.status,'cancelled');
 assert.ok((await use(a,'list_slots')).slots.some(x=>x.id==='S4'));
 expect(await use(resumed,'cancel_booking',{booking_id:booked.booking.id,expected_version:cancelled.version,request_id:'cancel-fresh'}),'already_cancelled');
 const dropped=expect(await use(a,'select_slot',{slot_id:'S4',expected_version:cancelled.version,request_id:'discard-pick'}),'committed');
 const discArgs={reservation_id:dropped.reservation.id,expected_version:dropped.version,request_id:'discard'};
 expect(await use(a,'discard_reservation',discArgs),'committed');
 assert.equal((await use(a,'discard_reservation',discArgs)).duplicate,true);
 const afterDisc=expect(await snap(i));
 expect(await i.call('env.apply_event',{expected_version:afterDisc.version,event:{...event,event_id:'no-open'}}),'invalid_event');
 assert.deepEqual(only(await snap(i)),only(afterDisc));
 for(let pass=0;pass<2;pass++){
  const now=expect(await snap(i));
  const reset=expect(await i.call('env.reset',{expected_version:now.version}),'ready');
  const resetSnap=expect(await snap(i));assert.deepEqual(only(resetSnap),only(initial));
  assert.deepEqual(resetSnap.snapshot.receipts,{});assert.ok(reset.version.epoch>now.version.epoch);
  const re=expect(await use(a,'select_slot',{slot_id:'S1',expected_version:reset.version,request_id:'first-choice'}),'committed');
  assert.equal(re.duplicate,undefined);assert.equal(re.reservation.id,chosen.reservation.id);
  expect(await i.call('env.apply_event',{event,expected_version:re.version}),'committed');
  assert.equal((await use(resumed,'get_reservation',{reservation_id:re.reservation.id})).reservation.status,'invalidated');
 }
 const ctrlI=make('infra','no-alts'),ctrlA=make('agent','no-alts');
 await Promise.all([ctrlI.initialize(),ctrlA.initialize()]);
 const baseline=expect(await snap(ctrlI));const limited=structuredClone(baseline.snapshot.data);limited.constraints.budget_minor=10000;
 const limitedLoad=expect(await ctrlI.call('env.load_seed',{data:limited,expected_version:baseline.version,virtual_now:at0,bundle:baseline.snapshot.resources.bundle,request_id:'limited-seed'}),'ready');
 const pick=expect(await use(ctrlA,'select_slot',{slot_id:'S1',expected_version:limitedLoad.version,request_id:'no-alt-select'}),'committed');
 expect(await ctrlI.call('env.apply_event',{event,expected_version:pick.version}),'committed');
 const none=expect(await use(ctrlA,'list_slots'));assert.deepEqual(none.slots,[]);assert.equal(none.booking_ids.length,8);
 console.log('PASS: real stdio MCP two-session race, exact replay/conflict, stale/invalidated/reconfirmed denial, atomic move/cancel, scoped no-result, and two fresh reset/replays.');
}
main().catch(e=>{console.error(e);process.exitCode=1;}).finally(async()=>{await Promise.allSettled(clients.map(c=>c.close()));staged.cleanup();fs.rmSync(state,{force:true,recursive:true});});
