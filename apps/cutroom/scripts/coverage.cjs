'use strict';
// Reproducible coverage report over CutRoom records.
//   node apps/cutroom/scripts/coverage.cjs [seed.json] [--write]
// Counts represented occurrence dates (not file times) in the studio time zone.
// `--write` refreshes evidence/coverage.json and evidence/coverage.md.
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const root=path.resolve(__dirname,'..');
const WINDOW=['2025-01-01','2026-12-31'];

// Every dated field the App stores, with the source it belongs to.
function events(data){
  const rows=[],add=(source,record_id,field,at)=>{if(at)rows.push({source,record_id,field,at});};
  for(const p of data.projects){
    add('releases',p.id,'published_at',p.published_at);
    add('schedules',p.id,'schedule.at',p.schedule?.at);
    for(const c of p.cuts){
      for(const n of c.notes){add('review_notes',`${p.id}/${c.id}/${n.id}`,'at',n.at);add('review_notes',`${p.id}/${c.id}/${n.id}`,'resolved_at',n.resolved_at);}
      for(const r of c.results)add('ab_results',`${p.id}/${c.id}/${r.asset_id}`,'at',r.at);
    }
    for(const g of p.guest_releases)for(const h of g.history)add('guest_releases',`${p.id}/${g.id}`,`history.${h.status}`,h.at);
    for(const o of p.overrides)add('overrides',p.id,'at',o.at);
  }
  for(const t of data.library){
    for(const h of t.history)add('licenses',t.id,`history.${h.status}`,h.at);
    add('licenses',t.id,'expires_at',t.expires_at);
  }
  return rows;
}
function localDate(at,timeZone){
  const parts=Object.fromEntries(new Intl.DateTimeFormat('en-CA',{timeZone,year:'numeric',month:'2-digit',day:'2-digit'})
    .formatToParts(new Date(at)).map(x=>[x.type,x.value]));
  return `${parts.year}-${parts.month}-${parts.day}`;
}
function coverage(data,{clock}={}){
  const tz=data.timezone, rows=events(data), invalid=[], outside=[], inWindow=[];
  for(const r of rows){
    if(Number.isNaN(Date.parse(r.at))){invalid.push(r);continue;}
    const date=localDate(r.at,tz), x={...r,date,month:date.slice(0,7),planned:clock?Date.parse(r.at)>Date.parse(clock):false};
    (date<WINDOW[0]||date>WINDOW[1]?outside:inWindow).push(x);
  }
  const months=[];for(let y=2025;y<=2026;y++)for(let m=1;m<=12;m++)months.push(`${y}-${String(m).padStart(2,'0')}`);
  const distinct=list=>new Set(list.map(x=>x.date)).size;
  const sources=[...new Set(inWindow.map(x=>x.source))].sort();
  const by_month=months.map(month=>{
    const m=inWindow.filter(x=>x.month===month);
    return {month,records:m.length,distinct_dates:distinct(m),past_dates:distinct(m.filter(x=>!x.planned)),planned_dates:distinct(m.filter(x=>x.planned)),
      by_source:Object.fromEntries(sources.map(s=>[s,m.filter(x=>x.source===s).length]).filter(([,v])=>v))};
  });
  const dates=[...new Set(inWindow.map(x=>x.date))].sort();
  return {scope:'CutRoom Environment evaluation dataset',timezone:tz,window:WINDOW,clock:clock??null,
    total_dated_fields:rows.length,in_window:inWindow.length,outside_window:outside.length,invalid:invalid.length,
    projects:data.projects.length,library_items:data.library.length,
    distinct_dates:dates.length,distinct_past_dates:distinct(inWindow.filter(x=>!x.planned)),distinct_planned_dates:distinct(inWindow.filter(x=>x.planned)),
    earliest:dates[0]??null,latest:dates.at(-1)??null,
    per_source:Object.fromEntries(sources.map(s=>{const l=inWindow.filter(x=>x.source===s);return [s,{fields:l.length,distinct_dates:distinct(l)}];})),
    months_without_records:by_month.filter(m=>!m.records).map(m=>m.month),
    provenance:{synthetic_fields:inWindow.length,real_fields:0,mixed_fields:0},
    by_month,outside_details:outside.map(({source,record_id,field,date})=>({source,record_id,field,date}))};
}
function markdown(r,file,sha){
  const src=Object.keys(r.per_source);
  return [`# CutRoom dataset coverage`,'',
  `Generated by \`node apps/cutroom/scripts/coverage.cjs ${file} --write\`. Do not edit by hand.`,'',
  `- Input: \`apps/cutroom/${file}\` (sha256 \`${sha}\`)`,
  `- Time zone: \`${r.timezone}\`; window ${r.window[0]} to ${r.window[1]}; clock \`${r.clock}\``,
  `- Records: ${r.projects} projects, ${r.library_items} library items; ${r.in_window} dated fields in window, ${r.outside_window} outside, ${r.invalid} invalid`,
  `- Distinct dates: **${r.distinct_dates}** (${r.distinct_past_dates} on or before the clock, ${r.distinct_planned_dates} planned after it); earliest ${r.earliest}, latest ${r.latest}`,
  `- Months without records: ${r.months_without_records.length?r.months_without_records.join(', '):'none'}`,
  `- Provenance: all ${r.provenance.synthetic_fields} fields are synthetic (no real or mixed records)`,'',
  `Planned dates are fields that exist at the clock and point forward: scheduled releases and license expiries. No note, signing or release after the clock is stored as a past fact.`,'',
  `| Month | Fields | Distinct dates | Past | Planned | ${src.join(' | ')} |`,
  `| --- | ---: | ---: | ---: | ---: | ${src.map(()=>'---:').join(' | ')} |`,
  ...r.by_month.map(m=>`| ${m.month} | ${m.records} | ${m.distinct_dates} | ${m.past_dates} | ${m.planned_dates} | ${src.map(s=>m.by_source[s]??0).join(' | ')} |`),'',
  `## Per source`,'','| Source | Fields | Distinct dates |','| --- | ---: | ---: |',
  ...src.map(s=>`| ${s} | ${r.per_source[s].fields} | ${r.per_source[s].distinct_dates} |`),'',
  `## Outside the window`,'',r.outside_details.length?r.outside_details.map(x=>`- ${x.source} \`${x.record_id}\` ${x.field} ${x.date}`).join('\n'):'None.',''].join('\n');
}
module.exports={events,coverage,localDate};
if(require.main===module){
  const file=process.argv.slice(2).find(a=>!a.startsWith('--'))||'datasets/history/seed.json';
  const bytes=fs.readFileSync(path.join(root,file)),data=JSON.parse(bytes);
  const clock=JSON.parse(fs.readFileSync(path.join(root,'fixtures/clock.json'),'utf8')).initial_time;
  const report=coverage(data,{clock}),sha=crypto.createHash('sha256').update(bytes).digest('hex');
  if(process.argv.includes('--write')){
    fs.mkdirSync(path.join(root,'evidence'),{recursive:true});
    fs.writeFileSync(path.join(root,'evidence/coverage.json'),JSON.stringify({input:file,sha256:sha,...report},null,2)+'\n');
    fs.writeFileSync(path.join(root,'evidence/coverage.md'),markdown(report,file,sha));
  }
  const {by_month,outside_details,...summary}=report;
  console.log(JSON.stringify({input:file,sha256:sha,...summary},null,2));
}
