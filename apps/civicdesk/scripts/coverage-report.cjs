'use strict';
// Reproducible coverage report for the delivered evaluation data (docs/submission-evidence.md, section 3).
// Counts represented occurrence dates, not file dates, in one declared time zone, over 2025-01-01 .. 2026-12-31.
//   node apps/civicdesk/scripts/coverage-report.cjs            writes evidence/coverage.json and evidence/coverage.md
const fs = require('node:fs'), path = require('node:path'), crypto = require('node:crypto');
const root = path.resolve(__dirname, '..');
const WINDOW = {start:'2025-01-01', end:'2026-12-31'}, TZ = 'America/Los_Angeles';
const seedPath = path.join(root, 'fixtures/minimal.json'), raw = fs.readFileSync(seedPath), data = JSON.parse(raw);
const clock = JSON.parse(fs.readFileSync(path.join(root, 'fixtures/clock.json'), 'utf8')).initial_time;
const fmt = new Intl.DateTimeFormat('en-CA', {timeZone:TZ, year:'numeric', month:'2-digit', day:'2-digit'});
const dayOf = value => /^\d{4}-\d{2}-\d{2}$/.test(value) ? value : fmt.format(new Date(value));
const inWindow = day => day >= WINDOW.start && day <= WINDOW.end;
const month = day => day.slice(0, 7);
const agencyTz = id => data.agencies.find(a => a.agency_id === id).timezone;
const SOURCES = [
  {source:'dockets', records:data.dockets, primary:d => d.opened_at, dates:d => [d.opened_at, d.closes_at, d.extended_from, d.created_at, d.updated_at, ...d.corrections.map(x => x.at), ...d.history.map(h => h.at)].filter(Boolean)},
  {source:'comment_periods_closing', records:data.dockets, primary:d => d.closes_at, dates:d => [d.closes_at]},
  {source:'documents', records:data.documents, primary:x => x.published_at, dates:x => [x.published_at]},
  {source:'comments', records:data.comments, primary:x => x.submitted_at, dates:x => [x.submitted_at, x.updated_at, ...x.notices.map(n => n.at), ...x.history.map(h => h.at)]},
  {source:'drafts', records:data.drafts, primary:r => r.created_at, dates:r => [r.created_at, r.updated_at]}
];
const months = [];
for (let y = 2025; y <= 2026; y++) for (let m = 1; m <= 12; m++) months.push(y + '-' + String(m).padStart(2, '0'));
const global = new Set(), globalInWindow = new Set(), invalid = [];
const bySource = SOURCES.map(({source, records, primary, dates}) => {
  const distinct = new Set(), perMonth = Object.fromEntries(months.map(m => [m, 0]));
  let earliest = null, latest = null, outOfWindow = 0, future = 0;
  for (const r of records) {
    for (const v of dates(r)) {
      if (!v || !Number.isFinite(Date.parse(v.length === 10 ? v + 'T12:00:00Z' : v))) {invalid.push({source, value:v}); continue;}
      const d = dayOf(v); distinct.add(d); global.add(d); if (inWindow(d)) globalInWindow.add(d);
    }
    const d = dayOf(primary(r));
    if (!inWindow(d)) {outOfWindow++; continue;}
    perMonth[month(d)]++;
    if (earliest === null || d < earliest) earliest = d;
    if (latest === null || d > latest) latest = d;
    if (Date.parse(primary(r).length === 10 ? primary(r) + 'T23:59:59Z' : primary(r)) > Date.parse(clock)) future++;
  }
  return {source, records:records.length, distinct_dates:[...distinct].filter(inWindow).length, earliest, latest, out_of_window:outOfWindow, after_clock:future, per_month:perMonth};
});
const primaryByMonth = Object.fromEntries(months.map(m => [m, bySource.reduce((s, x) => s + x.per_month[m], 0)]));
const historyByMonth = Object.fromEntries(months.map(m => [m, bySource.reduce((s, x) => s + x.per_month[m], 0)]));
const gaps = months.filter(m => historyByMonth[m] === 0);
const report = {
  schema:'pale.environment-coverage-report.v1', app_id:'civicdesk', dataset:'contribution/dataset.json', fixture:'fixtures/minimal.json',
  fixture_sha256:crypto.createHash('sha256').update(raw).digest('hex'), generator:'scripts/generate-fixture.cjs (seed 20261130)',
  window:WINDOW, time_zone:TZ, clock, counting:'Each dated field is normalized to a calendar date in the member time zone (deadlines themselves are stored in the agency time zone). A record is placed in the month of its represented occurrence date (docket opening, period closing, document publication, comment submission, draft creation). Dates after the clock are comment periods still open, labeled after_clock.',
  provenance:{real:0, synthetic:bySource.reduce((s, x) => s + x.records, 0), note:'Every record is generated by scripts/generate-fixture.cjs; no real agencies, rules, documents or comments. Rules and notice text are authored; periods, documents and the comment history are computed.'},
  totals:{records:bySource.reduce((s, x) => s + x.records, 0), distinct_dates_all:global.size, distinct_dates_in_window:globalInWindow.size, invalid_dates:invalid.length},
  sources:bySource, per_month:{all_sources:primaryByMonth, all_sources_again:historyByMonth},
  gaps:{months_without_history_records:gaps, note:gaps.length ? 'Months with no represented record.' : 'Every month in the window holds at least one history record.'}
};
fs.mkdirSync(path.join(root, 'evidence'), {recursive:true});
fs.writeFileSync(path.join(root, 'evidence/coverage.json'), JSON.stringify(report, null, 2) + '\n');
const md = ['# Data coverage: CivicDesk fixture', '',
  'Window **' + WINDOW.start + ' to ' + WINDOW.end + '**, time zone `' + TZ + '`, clock `' + clock + '`. Fixture `fixtures/minimal.json` (SHA-256 `' + report.fixture_sha256 + '`), generated by `scripts/generate-fixture.cjs`; all ' + report.totals.records + ' records are synthetic.', '',
  'Reproduce: `node apps/civicdesk/scripts/coverage-report.cjs` (rewrites this file and `coverage.json`).', '',
  '| Source | Records | Distinct dates in window | Earliest | Latest | After clock |', '| --- | ---: | ---: | --- | --- | ---: |',
  ...bySource.map(x => '| ' + x.source + ' | ' + x.records + ' | ' + x.distinct_dates + ' | ' + (x.earliest || '—') + ' | ' + (x.latest || '—') + ' | ' + x.after_clock + ' |'),
  '', 'Global deduplicated distinct dates in window: **' + globalInWindow.size + '** (' + global.size + ' including dates outside the window). Invalid dates: ' + invalid.length + '.', '',
  '| Month | Records | All sources |', '| --- | ---: | ---: |',
  ...months.map(m => '| ' + m + ' | ' + historyByMonth[m] + ' | ' + primaryByMonth[m] + ' |'),
  '', (gaps.length ? 'Months without records: ' + gaps.join(', ') + '. ' : 'Every month in the window holds at least one record. ') + 'Open comment periods extend past the clock into January 2027; those closing instants fall outside the window and are reported as out_of_window.', ''];
fs.writeFileSync(path.join(root, 'evidence/coverage.md'), md.join('\n'));
console.log(JSON.stringify({records:report.totals.records, distinct_dates_in_window:globalInWindow.size, gaps, invalid:invalid.length}));
