'use strict';
const fs = require('node:fs');
const path = require('node:path');
const plugin = require('../../plugin.cjs');
const {hash} = require('../../src/common.cjs');
const {definitions,initial_time} = require('./definitions.cjs');
const root = path.resolve(__dirname,'../../fixtures/scenarios');
const copy = value => structuredClone(value);
const json = value => JSON.stringify(value,null,2)+'\n';
function build(definition) {
  let data = copy(require('../../fixtures/minimal.json'));
  const ctx = {app_id:'stayready',run_id:'fixture-authoring',role:'agent',binding:copy(require('../../fixtures/binding.json')),virtual_now:'2026-12-01T17:00:00Z'};
  const trace = [];
  function call(name,args) {const result=plugin.handleTool(ctx,data,name,args);data=result.data;trace.push({at:ctx.virtual_now,name,args:copy(args),result:copy(result.result),state_sha256:hash(data)});return result.result;}
  for (const history of definition.bootstrap) {
    ctx.virtual_now=history.at;
    const args={need_id:history.need_id,action:history.action};
    const preview=call('stayready.request.preview',args).preview;
    call('stayready.request.submit',{...args,preview_token:preview.preview_token});
    ctx.virtual_now=history.event.at;
    data=plugin.applyEvent({...ctx,role:'infra'},data,copy(history.event));
    trace.push({at:ctx.virtual_now,event:copy(history.event),outcome:copy(data.history.at(-1)),state_sha256:hash(data)});
  }
  plugin.validateSeed(ctx,data);
  return {data,trace};
}
function generate() {
  fs.mkdirSync(root,{recursive:true});
  const entries=[];
  for (const definition of definitions) {
    const {data,trace}=build(definition),directory=path.join(root,definition.id.toLowerCase());
    fs.mkdirSync(directory,{recursive:true});
    const plan={id:definition.id,title:definition.title,initial_time,seed:'seed.json',events:'events.json',bootstrap_trace:'bootstrap-trace.json',
      histories:definition.bootstrap.length,event_inputs:definition.bootstrap.length+definition.events.length,
      no_action_pass:Boolean(definition.no_action_pass),goal:definition.goal,representative_failure:definition.failure,
      executions:{reference:definition.reference,no_action:[],incorrect:definition.incorrect},
      scope:'App-only business calls and static events. Core receipt/epoch/policy claims require the separate real MCP report.'};
    fs.writeFileSync(path.join(directory,'seed.json'),json(data));
    fs.writeFileSync(path.join(directory,'events.json'),json({bootstrap:definition.bootstrap.map(x=>x.event),run:definition.events}));
    fs.writeFileSync(path.join(directory,'bootstrap-trace.json'),json(trace));
    fs.writeFileSync(path.join(directory,'plan.json'),json(plan));
    entries.push({id:definition.id,directory:definition.id.toLowerCase(),seed_sha256:hash(data),histories:data.requests.length,event_inputs:plan.event_inputs});
  }
  fs.writeFileSync(path.join(root,'manifest.json'),json({schema:'stayready.fixture-controls.v1',app_version:'0.1.0',initial_time,
    generator:'examples/fixtures/generate.cjs',binding:'../binding.json',policies:'../policies.json',baseline:'../minimal.json',
    provenance:'Authored synthetic hotel scenarios; no real guest data or media. Each seed is generated by public plugin business calls and unchanged, prewritten hotel events.',
    answer_labels:'Goals and control labels live in evaluation-side plan files, never in Agent-facing seed records.',scenarios:entries}));
  console.log('Generated 6 scenario seeds, each with 2 real request/reply histories and 6 fixed event inputs.');
}
if(require.main===module)generate();
module.exports={build,generate};
