'use strict';
// Coverage report for the delivery dataset (docs/submission-evidence.md, section 3): records and distinct
// dates per month, per family and per date field, counted in the provider's declared time zone, with gaps.
// It counts the records actually delivered in datasets/<family>/seed.json.
// Run: node scripts/coverage-report.cjs   (writes datasets/coverage.json and datasets/coverage.md)
//      node scripts/coverage-report.cjs --check
const fs = require('node:fs'), path = require('node:path'), crypto = require('node:crypto');
const DIR = path.resolve(__dirname, '../datasets');
const WINDOW = ['2025-01-01', '2026-12-31'];
const FIELDS = [
  ['cases', 'case opened_at', d => d.cases.map(c => c.opened_at)],
  ['turns', 'transcript turn at', d => d.cases.flatMap(c => c.transcript.map(t => t.at))],
  ['offers', 'offer presented_at', d => d.offers.map(o => o.presented_at)],
  ['commitments', 'commitment accepted_at', d => d.commitments.map(m => m.accepted_at)],
  ['reports', 'report at', d => d.commitments.flatMap(m => m.reports.map(r => r.at))],
  ['articles', 'article revision at (updated_at is the latest)', d => d.help_articles.flatMap(a => a.revisions.map(r => r.at))]
];
const months = []; for (let y = 2025; y <= 2026; y++) for (let m = 1; m <= 12; m++) months.push(`${y}-${String(m).padStart(2, '0')}`);

// Calendar date of a timestamp in the given IANA time zone.
const dayIn = zone => iso => new Intl.DateTimeFormat('en-CA', {timeZone: zone, year: 'numeric', month: '2-digit', day: '2-digit'}).format(new Date(iso));

function report() {
  const out = {schema: 'counterline.coverage.v1', window: WINDOW, provenance: 'synthetic: generated by scripts/generate-dataset.cjs through Counterline\'s own operations; no real or website data',
    counting: 'Each timestamp is converted to the provider\'s declared IANA time zone before its calendar date is taken. Records outside the window are excluded and listed. Distinct dates are deduplicated across all fields of a family.', families: {}};
  const combined = new Set();
  for (const family of ['card-issuer', 'internet-provider']) {
    const text = fs.readFileSync(path.join(DIR, family, 'seed.json'), 'utf8'), data = JSON.parse(text), day = dayIn(data.provider.time_zone);
    const f = {seed: `datasets/${family}/seed.json`, sha256: crypto.createHash('sha256').update(text).digest('hex'), time_zone: data.provider.time_zone, fields: {}, monthly: {}, excluded: []};
    const all = new Set();
    for (const m of months) f.monthly[m] = {};
    for (const [key, label, get] of FIELDS) {
      const dates = [];
      for (const t of get(data)) { const d = day(t); if (d < WINDOW[0] || d > WINDOW[1]) f.excluded.push({field: label, at: t}); else dates.push(d); }
      dates.sort();
      dates.forEach(d => { all.add(d); combined.add(d); });
      f.fields[key] = {date_field: label, records: dates.length, distinct_dates: new Set(dates).size, earliest: dates[0] || null, latest: dates.at(-1) || null};
      for (const m of months) f.monthly[m][key] = dates.filter(d => d.startsWith(m)).length;
    }
    for (const m of months) f.monthly[m].distinct_dates = [...all].filter(d => d.startsWith(m)).length;
    f.distinct_dates = all.size;
    f.gaps = months.filter(m => !f.monthly[m].cases);
    out.families[family] = f;
  }
  out.combined_distinct_dates = combined.size;
  return out;
}

function markdown(r) {
  const lines = ['# Counterline delivery dataset coverage', '', `Window ${r.window[0]} to ${r.window[1]}. ${r.provenance}.`, '', r.counting, ''];
  for (const [family, f] of Object.entries(r.families)) {
    lines.push(`## ${family}`, '', `Seed \`${f.seed}\` (sha256 \`${f.sha256.slice(0, 16)}…\`), counted in ${f.time_zone}. ${f.distinct_dates} distinct dates; months without a case: ${f.gaps.length ? f.gaps.join(', ') : 'none'}; records outside the window: ${f.excluded.length}.`, '',
      '| Field | Records | Distinct dates | Earliest | Latest |', '| :--- | ---: | ---: | :--- | :--- |',
      ...Object.values(f.fields).map(x => `| ${x.date_field} | ${x.records} | ${x.distinct_dates} | ${x.earliest} | ${x.latest} |`), '',
      '| Month | Cases | Turns | Offers | Commitments | Reports | Article revisions | Distinct dates |', '| :--- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |',
      ...Object.entries(f.monthly).map(([m, x]) => `| ${m} | ${x.cases} | ${x.turns} | ${x.offers} | ${x.commitments} | ${x.reports} | ${x.articles} | ${x.distinct_dates} |`), '');
  }
  lines.push(`Combined distinct dates across both families: ${r.combined_distinct_dates}.`, '');
  return lines.join('\n');
}

if (require.main === module) {
  const r = report(), files = [['coverage.json', JSON.stringify(r, null, 2) + '\n'], ['coverage.md', markdown(r)]];
  const check = process.argv.includes('--check'), drift = files.filter(([n, c]) => !fs.existsSync(path.join(DIR, n)) || fs.readFileSync(path.join(DIR, n), 'utf8') !== c);
  if (check) { if (drift.length) { console.error('Coverage report drift: ' + drift.map(d => d[0]).join(', ')); process.exit(1); } console.log('Coverage report is up to date.'); }
  else { for (const [n, c] of files) fs.writeFileSync(path.join(DIR, n), c); for (const [fam, f] of Object.entries(r.families)) console.log(`${fam}: ${f.distinct_dates} distinct dates, gaps ${JSON.stringify(f.gaps)}, excluded ${f.excluded.length}`); }
}
module.exports = {report};
