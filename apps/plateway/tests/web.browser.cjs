  const placed = after.find(o => o.id === first);
  check('Place order creates exactly one order to the previewed address, charged the previewed total', after.length === before.length + 1 && placed && placed.charge.amount_cents === charged && placed.tip_cents === 300 && placed.address_id === 'a-1' && placed.mode === 'asap');
