  check('Editing the tip removes the total on screen at once', await page.locator('[data-action=place-order]').count() === 0);
  await page.locator('[data-action=preview]').click();
  await page.locator('[data-total="' + (quoted.total_cents + 100) + '"]').waitFor();
  check('One click on Preview after editing the tip shows the new total');
