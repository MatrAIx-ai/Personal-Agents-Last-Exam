  const quoted = await t.host.client.call('plateway.checkout.preview', { address_id: 'a-1', card_id: 'c-1', when: { mode: 'asap' }, tip_cents: 200 });
  const rows = [...quoted.lines.map(l => ['[data-quote-line="' + l.id + '"]', [money(l.subtotal_cents)]]), ['[data-fee=delivery]', [money(quoted.fees.delivery_cents)]], ['[data-fee=service]', [money(quoted.fees.service_cents)]], ['[data-fee=tax]', [money(quoted.tax_cents)]], ['[data-fee=tip]', [money(quoted.tip_cents)]], ...(quoted.fees.small_order_cents ? [['[data-fee=small_order]', [money(quoted.fees.small_order_cents)]]] : [])];
  let itemised = total === quoted.total_cents && quoted.fees.small_order_cents > 0 && (await page.locator('[data-quote-line]').allInnerTexts()).every(x => !/tax/i.test(x));
  for (const [selector, values] of rows) { const text = await page.locator(selector).innerText(); itemised = itemised && values.every(v => text.includes(v)); }
  const destination = await page.locator('[data-quote-for]').innerText();
  check('Preview shows every line subtotal, each fee (including the small-order fee), tax once, tip and the total as the App computes them, with the address and card, and stores nothing', itemised && destination.includes('Home — 48 Linden Court') && destination.includes('Orbit •••• 4242') && JSON.stringify(await t.version()) === JSON.stringify(versionBeforePreview));
