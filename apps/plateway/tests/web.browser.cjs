  const { page, check } = t;
  const at = id => page.locator('[data-' + id + ']');
  const nav = name => page.locator('nav').getByRole('button', { name: new RegExp('^\\S*\\s*' + name) }).click();
  const alert = code => ({ waitFor: async () => { await page.locator('[role=alert][data-code=' + code + ']').first().waitFor(); await t.settled(); }, filter: f => ({ waitFor: async () => { await page.locator('[role=alert][data-code=' + code + ']').filter(f).first().waitFor(); await t.settled(); } }) });
