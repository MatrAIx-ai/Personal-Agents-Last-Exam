  check('Clear cart empties the cart and keeps the dish open with Add available again', (await cart()).lines.length === 0 && await page.locator('[data-action=add-to-cart]').count() === 1);
  await page.locator('[data-action=add-to-cart]').click();
  await flash('Added Elote');
