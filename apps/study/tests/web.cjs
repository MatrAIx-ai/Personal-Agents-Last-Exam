'use strict';
const fs=require('node:fs'), os=require('node:os'), path=require('node:path'), assert=require('node:assert/strict');
const {chromium}=require(process.env.PALE_PLAYWRIGHT_MODULE||'playwright');
const runtime=process.env.PALE_RUNTIME_ROOT||path.resolve(__dirname,'../../../runtime');
const {prepare}=require(path.join(runtime,'prepare.cjs')), {start}=require(path.join(runtime,'web/server.cjs'));
const {Client}=require(path.join(runtime,'client.cjs'));
async function run(){
 const stateDir=fs.mkdtempSync(path.join(os.tmpdir(),'study-browser-'));
 const assembly=prepare(path.resolve(__dirname,'..'));
 const opts={registry:assembly.registry},run='study-browser',profile='sandbox';
 const hosts=[]; let browser,infra,agent,observerInfra;
 const ok=(x,status='committed')=>{assert.equal(x.status,status,JSON.stringify(x));return x;};
 try{
  const host=await start({app:'study',...opts,profile,run,stateDir}); hosts.push(host);
  const observer=await start({app:'study',...opts,profile:'scenario',run:'study-observer',stateDir}); hosts.push(observer);
  infra=new Client('study','infra',run,stateDir,'browser-infra',opts); await infra.initialize();
  agent=new Client('study','agent',run,stateDir,'second-agent',opts); await agent.initialize();
  observerInfra=new Client('study','infra','study-observer',stateDir,'observer-infra',opts); await observerInfra.initialize();
  const snap=()=>infra.call('env.snapshot');
  const before=(await snap()).snapshot, observerBefore=(await observerInfra.call('env.snapshot')).snapshot;
  browser=await chromium.launch({chromiumSandbox:true,...(process.env.CHROMIUM_PATH?{executablePath:process.env.CHROMIUM_PATH}:{})});
  const context=await browser.newContext({viewport:{width:950,height:780}});
  const p=await context.newPage(), errors=[]; p.on('pageerror',e=>errors.push(e.message));
  const b=n=>p.getByRole('button',{name:n,exact:true}), t=s=>p.getByText(s,{exact:true}), seen=s=>t(s).waitFor(), click=n=>b(n).click();
  const call=(n,a={})=>agent.call('study.'+n,a);
  await p.goto(host.accessUrl);
  await b('Reveal Train station').waitFor();
  assert.equal(await t('estación de tren').count(),0);
  await click('Decks'); await click('Open Train station');
  const prompt=p.getByRole('textbox',{name:'Prompt',exact:true});
  await prompt.fill('Discarded station'); await click('Discard card form');
  assert.equal((await call('get_card',{card_id:'C1'})).card.prompt,'Train station');
  await click('Open Train station'); await prompt.fill('Station entrance'); await click('Save card'); await b('Open Station entrance').waitFor();
  await click('Open Station entrance'); await click('Suspend card'); await seen('Card suspended.');
  await click('Queue'); await b('Reveal Open today').waitFor(); assert.equal(await b('Reveal Station entrance').count(),0);
  await click('Decks'); await click('Open Station entrance'); await click('Restore card'); await seen('Card restored.');
  assert.equal((await call('get_card',{card_id:'C1'})).card.suspended,false);
  await click('Plan'); await click('Edit plan');
  const target=p.getByRole('spinbutton',{name:'Target study day',exact:true});
  await target.fill('4'); await click('Preview plan'); await b('Save previewed plan').waitFor(); await target.fill('5');
  assert.equal(await b('Save previewed plan').count(),0); await click('Discard plan draft'); await seen('Target: study day 10');
  await click('Edit plan'); await target.fill('8'); await click('Preview plan'); await click('Save previewed plan'); await seen('Target: study day 8');
  await click('Edit plan'); await target.fill('7'); await click('Preview plan'); await b('Save previewed plan').waitFor();
  const q=await call('get_plan'); const plan=q.plan;
  ok(await call('save_plan',{deck_ids:plan.deck_ids,target_day:9,daily_limit:plan.daily_limit,new_limit:plan.new_limit,request_id:'other-plan-browser',expected_version:q.version}));
  await click('Save previewed plan'); await p.getByText(/observed version is stale/i).waitFor();
  await click('Refresh'); await seen('Target: study day 9');
  await click('Queue'); await click('Reveal Station entrance'); await seen('estación de tren'); await click('Close revealed card');
  assert.equal((await call('get_history')).history.length,0);
  await click('Reveal Station entrance'); await click('Pause at this card'); await seen('Session: paused · C1');
  await p.reload(); await seen('Session: paused · C1');
  assert.equal((await call('get_queue')).session.paused,true);
  await click('Resume session'); await seen('Session: active · C1');
  await click('Reveal Station entrance'); await click('Good'); await seen('Recorded: Good');
  await click('History'); await seen('C1 · day 0 · Good · due day 3');
  await click('Undo latest review'); await click('Keep review'); await seen('C1 · day 0 · Good · due day 3');
  await click('Undo latest review'); await click('Confirm undo'); await seen('C1 · day 0 · Good · due day 3 · Undone');
  const history=(await call('get_history')).history;
  assert.deepEqual(history.map(r=>[r.card_id,r.rating,r.undone]),[['C1','Good',true]]);
  await click('Queue'); await seen('Study day 0 · 3 review slots and 1 new-card slots left');
  await click('Reveal Station entrance'); await seen('estación de tren');
  const s=await call('get_card',{card_id:'C1'});
  ok(await infra.call('env.apply_event',{expected_version:s.version,event:{event_id:'correction-browser',at:'2027-01-08T09:00:00+08:00',operation:'study.correct_card',payload:{card_id:'C1',expected_revision:s.card.card_version,answer:'estación ferroviaria'}}}));
  await click('Good'); await p.getByText(/observed version is stale/i).waitFor();
  assert.deepEqual((await call('get_history')).history,history);
  await click('Refresh'); await click('Reveal Station entrance'); await seen('estación ferroviaria'); await click('Close revealed card');
  await click('Plan'); await seen('Study day 0 · Card corrected · C1');
  const latest=await call('get_plan');
  ok(await infra.call('env.apply_event',{expected_version:latest.version,event:{event_id:'target-browser',at:'2027-01-08T10:00:00+08:00',operation:'study.change_target',payload:{plan_id:'P1',expected_revision:latest.plan.revision,target_day:-1}}}));
  await click('Refresh'); await seen('Target: study day -1'); await seen('Daily review limit: 3');
  await p.getByText(/^Missing slots: [1-9][0-9]*$/).waitFor(); await seen('Study day 0 · Target changed · P1');
  await click('Decks'); await click('Add card to Everyday Spanish');
  await prompt.fill('Quiet room'); await p.getByRole('textbox',{name:'Answer',exact:true}).fill('sala tranquila');
  await click('Save card'); await b('Open Quiet room').waitFor();
  await p.goto(observer.accessUrl); await click('Reveal Train station'); await seen('Rating is disabled by the current study policy.');
  assert.equal(await p.getByRole('button',{name:/^(Again|Good|Pause at this card)$/}).count(),0);
  await click('Decks'); await click('Open Train station'); assert.equal(await p.getByRole('button',{name:/^(Save card|Suspend card|Add card.*)$/}).count(),0);
  await click('Plan'); await b('Try plan preview').waitFor(); assert.equal(await b('Edit plan').count(),0);
  for(let n=0;n<2;n++){
    ok(await infra.call('env.reset',{expected_version:(await snap()).version}),'ready');
    const after=(await snap()).snapshot;
    assert.deepEqual(after.data,before.data); assert.equal(after.virtual_now,before.virtual_now);
    assert.deepEqual((await observerInfra.call('env.snapshot')).snapshot.data,observerBefore.data);
  }
  await p.goto(host.url); await b('Reveal Train station').waitFor(); assert.equal(await b('Reveal Station entrance').count(),0);
  assert.deepEqual(errors,[]);
  console.log('PASS Chromium: card save/discard/suspend, plan preview/discard/commit/stale, pause/reload, review/undo, correction/stale, target/capacity, observer and two resets.');
 }finally{await browser?.close(); await Promise.all([infra?.close(),agent?.close(),observerInfra?.close(),...hosts.map(h=>h.close())]); assembly.cleanup(); fs.rmSync(stateDir,{recursive:true,force:true});}
}
run().catch(e=>{console.error(e);process.exitCode=1;});
