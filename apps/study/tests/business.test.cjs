'use strict';
const {test}=require('node:test'),assert=require('node:assert/strict');
const {handleTool,validateSeed}=require('../plugin.cjs');
const start=require('../fixtures/minimal.json');
const day0={virtual_now:'2027-01-07T16:00:00Z'};
const call=(s,key,args={},ctx=day0)=>handleTool(ctx,s,'study.'+key,args).result;
const rate=(s,card_id,rating,review_day=0,ctx=day0)=>call(s,'record_review',{card_id,rating,review_day,card_version:1},ctx);
test('queue order, no visible answers, and same-day capacity',()=>{
  const s=structuredClone(start); validateSeed(day0,s);
  assert.deepEqual(call(s,'get_queue').cards.map(x=>x.id),['C1','C4','C2']);
  assert.ok(call(s,'list_cards').cards.every(x=>!Object.hasOwn(x,'answer')));
  assert.equal(call(s,'reveal',{card_id:'C2'}).answer,'asiento de ventanilla');
  assert.equal(rate(s,'C2','Again').new_remaining,0);
  assert.throws(()=>rate(s,'C3','Good'),{code:'not_eligible'});
  assert.throws(()=>rate(s,'C2','Good'),{code:'not_eligible'});
  assert.equal(rate(s,'C1','Good').review.due_day,3);
  assert.equal(rate(s,'C4','Good').review.due_day,7);
  assert.equal(call(s,'get_queue').remaining,0);
  assert.equal(call(s,'get_history').history.length,3);
});
test('midnight, skipped days, overdue and stale form',()=>{
  const s=structuredClone(start);
  rate(s,'C1','Again');
  const day1={virtual_now:'2027-01-08T16:00:00Z'};
  assert.equal(call(s,'get_queue',{},day1).day,1);
  assert.throws(()=>rate(s,'C1','Good',0,day1),{code:'stale_review_day'});
  assert.throws(()=>call(s,'record_review',{card_id:'C1',rating:'Good',review_day:1,card_version:2},day1),{code:'stale_card'});
  const day5={virtual_now:'2027-01-13T09:00:00+08:00'};
  assert.deepEqual(call(s,'get_queue',{},day5).cards.map(x=>x.id),['C4','C1','C2']);
  assert.equal(call(s,'get_history',{},day5).history.length,1);
});
test('seed denies impossible constraints and dangling foreign references',()=>{
  const s=structuredClone(start);s.plan.new_limit=4;
  assert.throws(()=>validateSeed(day0,s),{code:'invalid_seed'});
  s.plan.new_limit=1;s.cards[1].deck_id='none';
  assert.throws(()=>validateSeed(day0,s),{code:'invalid_seed'});
});
test('edit, suspend and restore keep due day and append-only ledger',()=>{
  const s=structuredClone(start);
  const r=rate(s,'C1','Good').review;
  const card=call(s,'save_card',{card_id:'C1',deck_id:'D1',prompt:'Rail station',answer:'la estación'}).card;
  assert.equal(card.card_version,2);
  assert.equal(card.due_day,3);
  assert.equal(call(s,'set_suspension',{card_id:'C1',suspended:true}).card.suspended,true);
  assert.equal(call(s,'set_suspension',{card_id:'C1',suspended:false}).card.due_day,3);
  assert.deepEqual(call(s,'get_history').history,[r]);
  const added=call(s,'save_card',{deck_id:'D3',prompt:'Look here',answer:'Mira aquí'}).card;
  assert.equal(added.stage,0);assert.equal(added.due_day,0);assert.ok(call(s,'list_cards',{deck_id:'D3'}).cards.some(c=>c.id===added.id));
});
test('preview/discard, capacity shortfall, and explicit plan save',()=>{
  const s=structuredClone(start),before=structuredClone(s);
  const plan={deck_ids:['D3'],target_day:0,daily_limit:3,new_limit:1};
  const projected=call(s,'preview_plan',plan);
  assert.deepEqual(projected.capacity,{remaining_cards:32,due_now:32,available_slots:3,missing_slots:31});
  assert.deepEqual(s,before);
  const saved=call(s,'save_plan',plan);
  assert.equal(saved.plan.revision,before.plan.revision+1);
  assert.deepEqual(call(s,'get_capacity').capacity,saved.capacity);
  const extended=call(s,'preview_plan',{...plan,target_day:2});
  assert.equal(extended.capacity.missing_slots,29);
  const invalid=()=>call(s,'save_plan',{...plan,new_limit:4});
  assert.throws(invalid,{code:'invalid_plan'});
  assert.equal(call(s,'get_plan').plan.daily_limit,3);
});
test('pause/resume cursor, latest same-day undo, and repeat rating',()=>{
  const s=structuredClone(start);
  assert.deepEqual(call(s,'set_session',{card_id:'C2',paused:true}).session,{card_id:'C2',paused:true});
  assert.deepEqual(call(s,'get_queue').session,{card_id:'C2',paused:true});
  assert.throws(()=>call(s,'reveal',{card_id:'C2'}),{code:'session_paused'});
  assert.throws(()=>rate(s,'C2','Good'),{code:'session_paused'});
  call(s,'set_session',{card_id:'C2',paused:false});
  const first=rate(s,'C1','Good').review,latest=rate(s,'C2','Good').review;
  assert.throws(()=>call(s,'undo_review',{review_id:first.id}),{code:'not_undoable'});
  assert.equal(call(s,'get_history').undoable_review_id,latest.id);
  const undo=call(s,'undo_review',{review_id:latest.id});
  assert.equal(undo.review.undone,true);assert.equal(undo.new_remaining,1);
  assert.equal(undo.remaining,2);assert.equal(call(s,'get_card',{card_id:'C2'}).card.reviewed,false);
  assert.throws(()=>call(s,'undo_review',{review_id:latest.id}),{code:'not_undoable'});
  const r=call(s,'reveal',{card_id:'C2'});
  const again=call(s,'record_review',{card_id:'C2',card_version:r.card_version,review_day:r.review_day,rating:'Again'}).review;
  assert.notEqual(again.id,latest.id);assert.equal(again.stage,0);assert.equal(again.due_day,1);
  assert.equal(call(s,'get_history').history.length,3);
  const tomorrow={virtual_now:'2027-01-09T00:00:00+08:00'};
  assert.equal(call(s,'get_history',{},tomorrow).undoable_review_id,null);
});
