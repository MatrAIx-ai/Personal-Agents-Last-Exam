'use strict';
const assert=require('node:assert/strict'),path=require('node:path');
const root=process.env.PALE_RUNTIME_ROOT;
if(!root) throw Error('Set PALE_RUNTIME_ROOT to the pinned upstream runtime directory.');
const {prepare}=require(path.join(path.resolve(root),'prepare.cjs'));
const {Client}=require(path.join(path.resolve(root),'client.cjs'));
const p=prepare(path.resolve(__dirname,'..')), stateDir=path.join(p.root,'state');
const infra=new Client(p.app,'infra','library-demo',stateDir,'research-library-v1',{registry:p.registry});
const agent=new Client(p.app,'agent','library-demo',stateDir,'research-library-v1',{registry:p.registry});
async function demo() {
 const snapshot=()=>infra.call('env.snapshot');
 const expected=(r,s)=>{assert.equal(r.status,s,JSON.stringify(r));return r};
 const baseline=(s)=>[s.snapshot.data,s.snapshot.resources,s.snapshot.virtual_now];
 await infra.initialize();await agent.initialize();
 const unseeded=await snapshot();
 const seed=expected(await infra.call('env.load_seed',{expected_version:unseeded.version,request_id:'seed-1',data:unseeded.snapshot.data,binding:unseeded.snapshot.binding,policies:unseeded.snapshot.policies,bundle:unseeded.snapshot.resources.bundle,virtual_now:'2027-01-08T08:00:00Z'}),'ready');
 const atSeed=await snapshot();
 const s={library_id:'group-1'};
 const read=expected(await agent.call('library.search',{...s,tag:'methods'}),'ok');
 assert.equal(read.records[0].id,'paper-17');
 assert.deepEqual(expected(await agent.call('library.get',{...s,id:'paper-17'}),'ok').notes,[]);
 expected(await agent.call('library.search',{library_id:'private-a'}),'permission_denied');
 expected(await agent.call('env.snapshot',{}),'permission_denied');
 const imp={...s,request_id:'edit-1',expected_version:read.version,catalog_id:'catalog-18'};
 expected(await agent.call('library.import',imp),'permission_denied');
 assert.deepEqual(baseline(await snapshot()),baseline(atSeed));
 const pick={...s,record_ids:['paper-17']};
 const citation='@misc{paper-17,\n  title={Field Notes},\n  author={Avery Example},\n  year={2027}\n}\n';
 assert.equal(expected(await agent.call('library.preview_citations',pick),'ok').bibtex,citation);
 expected(await agent.call('library.export_citations',{...pick,request_id:'viewer-export',expected_version:seed.version}),'permission_denied');
 assert.deepEqual(baseline(await snapshot()),baseline(atSeed));
 const args={expected_version:seed.version,event:require('../examples/scenario.json')};
 const grant=expected(await infra.call('env.apply_event',args),'committed');
 assert.equal((await infra.call('env.apply_event',args)).duplicate,true);
 expected(await agent.call('library.import',{...imp,request_id:'stale-1'}),'stale_version');
 const refreshed=expected(await agent.call('library.search',s),'ok');assert.deepEqual(refreshed.version,grant.version);
 const write={...imp,request_id:'import-1',expected_version:refreshed.version};
 const imported=expected(await agent.call('library.import',write),'committed');
 assert.deepEqual(await agent.call('library.import',write),{...imported,duplicate:true});
 expected(await agent.call('library.import',{...write,expected_version:imported.version}),'idempotency_conflict');
 expected(await agent.call('library.import',{...write,request_id:'import-new',expected_version:imported.version}),'duplicate_import');
 const edited=expected(await agent.call('library.save_record',{...s,id:imported.record.id,request_id:'edit-ok',expected_version:imported.version,expected_record_revision:1,patch:{title:'Updated',reading_status:'reading'}}),'committed');
 const note=expected(await agent.call('library.save_note',{...s,id:edited.record.id,request_id:'note-ok',expected_version:edited.version,expected_record_revision:2,text:'Review this paper'}),'committed');
 assert.deepEqual(expected(await agent.call('library.get',{...s,id:edited.record.id}),'ok').notes,[note.note]);
 assert.deepEqual(expected(await agent.call('library.get',{...s,id:'paper-17'}),'ok').notes,[]);
 const doWrite=async(name,args,expected_version,request_id,status='committed')=>expected(await agent.call('library.'+name,{...s,...args,expected_version,request_id}),status);
 const created=await doWrite('create_collection',{name:'Methods'},note.version,'collection-1');
 const renamed=await doWrite('rename_collection',{collection_id:created.collection.id,name:'Methods Revised'},created.version,'rename-1');
 const membershipArgs={collection_id:renamed.collection.id,record_id:edited.record.id};
 const added=await doWrite('set_membership',{...membershipArgs,member:true},renamed.version,'member-1');
 assert.deepEqual(added.collection.member_ids,[edited.record.id]);
 const removed=await doWrite('set_membership',{...membershipArgs,member:false},added.version,'member-2');
 assert.deepEqual(removed.collection.member_ids,[]);
 assert.equal(expected(await agent.call('library.get',{...s,id:edited.record.id}),'ok').record.id,edited.record.id);
 const exported=await doWrite('export_citations',pick,removed.version,'export-1');
 assert.equal(exported.export.bibtex,citation);
 assert.deepEqual(await doWrite('export_citations',pick,removed.version,'export-1'),{...exported,duplicate:true});
 assert.deepEqual(expected(await agent.call('library.read_export',{...s,export_id:exported.export.id}),'ok').export,exported.export);
 const correction={event_id:'corr-1',at:'2027-01-08T09:05:00+00:00',operation:'library.catalog_correct',payload:{record_id:'paper-17',expected_revision:2,patch:{title:'Field Notes, Revised'}}};
 const bad={...correction,event_id:'bad',payload:{...correction.payload,expected_revision:1}};
 const beforeCorrection=await snapshot();
 expected(await infra.call('env.apply_event',{expected_version:exported.version,event:bad}),'invalid_event');
 assert.deepEqual(baseline(await snapshot()),baseline(beforeCorrection));
 const corrArgs={expected_version:exported.version,event:correction};
 const corrected=expected(await infra.call('env.apply_event',corrArgs),'committed');
 assert.equal((await infra.call('env.apply_event',corrArgs)).duplicate,true);
 assert.equal(expected(await agent.call('library.get',{...s,id:'paper-17'}),'ok').record.title,'Field Notes, Revised');
 assert.equal(expected(await agent.call('library.read_export',{...s,export_id:exported.export.id}),'ok').export.bibtex,citation);
 const discarded=await doWrite('trash_record',{id:'paper-17',expected_record_revision:3},corrected.version,'trash-1');
 expected(await agent.call('library.get',{...s,id:'paper-17'}),'not_found');
 expected(await agent.call('library.preview_citations',pick),'not_found');
 assert.deepEqual(expected(await agent.call('library.list_collections',s),'ok').collections[0].member_ids,[]);
 assert.equal(expected(await agent.call('library.list_trash',s),'ok').records[0].id,'paper-17');
 assert.deepEqual(await doWrite('trash_record',{id:'paper-17',expected_record_revision:3},corrected.version,'trash-1'),{...discarded,duplicate:true});
 const restored=await doWrite('restore_record',{id:'paper-17',expected_record_revision:4},discarded.version,'restore-1');
 assert.equal(restored.record.id,'paper-17');
 assert.deepEqual(expected(await agent.call('library.list_collections',s),'ok').collections[0].member_ids,['paper-17']);
 const after=await snapshot();assert.equal(after.snapshot.data.records.length,3);
 const changedClock=expected(await infra.call('env.advance_time',{expected_version:after.version,request_id:'expire',virtual_now:'2027-01-08T12:00:00Z'}),'committed');
 expected(await agent.call('library.search',s),'session_expired');
 assert.deepEqual((await snapshot()).snapshot.data,after.snapshot.data);
 const reset=expected(await infra.call('env.reset',{expected_version:changedClock.version}),'ready');
 assert.ok(reset.version.epoch>after.version.epoch);
 assert.deepEqual(baseline(await snapshot()),baseline(atSeed));
 expected(await agent.call('library.import',{...write,request_id:'reset-denial',expected_version:reset.version}),'permission_denied');
 console.log('PASS: real PALE stdio six workflow paths, scoped deny, exact citation bytes, replay, correction, expiry, snapshot and reset.');
}
demo().catch(e=>{console.error(e);process.exitCode=1;}).finally(async()=>{await Promise.allSettled([infra.close(),agent.close()]);p.cleanup()});
